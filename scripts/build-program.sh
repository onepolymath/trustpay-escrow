#!/usr/bin/env bash
# Builds the on-chain program and regenerates the IDL + TypeScript types used by the SDK.
#
# We call cargo-build-sbf directly (instead of `anchor build`) so we can pin a platform-tools
# release whose Cargo understands edition-2024 crates in the dependency tree.
set -euo pipefail
cd "$(dirname "$0")/.."

TOOLS_VERSION="${SBF_TOOLS_VERSION:-v1.57}"
# SBPF v0 is the bytecode version every cluster (and LiteSVM) executes today.
ARCH="${SBF_ARCH:-v0}"

cargo build-sbf \
  --tools-version "$TOOLS_VERSION" \
  --arch "$ARCH" \
  --manifest-path programs/trustpay/Cargo.toml \
  --sbf-out-dir target/deploy

mkdir -p target/idl target/types
anchor idl build -p trustpay -o target/idl/trustpay.json -t target/types/trustpay.ts

SDK_IDL=packages/sdk/src/idl
cp target/idl/trustpay.json "$SDK_IDL/trustpay.json"
cp target/types/trustpay.ts "$SDK_IDL/trustpay.ts"
{
  echo "// Generated by scripts/build-program.sh from target/idl/trustpay.json. Do not edit."
  echo "// Anchor's TS type is camelCase while the JSON IDL is snake_case; the Program class"
  echo "// converts at runtime, hence the cast (this is the standard Anchor pattern)."
  echo 'import type { Trustpay } from "./trustpay.js";'
  echo ""
  printf "export const IDL = "
  cat target/idl/trustpay.json
  echo " as unknown as Trustpay;"
} > "$SDK_IDL/idl.ts"

echo "Built target/deploy/trustpay.so ($(du -h target/deploy/trustpay.so | cut -f1)) and synced IDL into packages/sdk."
